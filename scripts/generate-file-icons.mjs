#!/usr/bin/env node
// Regenerates client/file-icons.ts: Paseo's file-type icons as PNG data URIs, because plugins
// cannot render SVG. Reads Paseo's vendored material-icon-theme table and tones the colours
// the way Paseo does (OKLab chroma scaled to 0.65), so the icons match its Changes panel.
//
//   git clone --depth 1 https://github.com/getpaseo/paseo /tmp/paseo-src
//   npm install --no-save @resvg/resvg-js
//   node scripts/generate-file-icons.mjs /tmp/paseo-src
import { Resvg } from "@resvg/resvg-js";
import { copyFileSync, mkdtempSync, writeFileSync, appendFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const paseoSource = process.argv[2];
if (!paseoSource) {
  console.error("Usage: node scripts/generate-file-icons.mjs <paseo checkout>");
  process.exit(1);
}

// The table's maps are module-private; copy the file and export them.
const scratch = join(mkdtempSync(join(tmpdir(), "file-icons-")), "material-file-icons.ts");
copyFileSync(join(paseoSource, "packages/app/src/components/material-file-icons.ts"), scratch);
appendFileSync(scratch, "\nexport { SVG_ICONS, EXTENSION_TO_ICON };\n");
const { SVG_ICONS, EXTENSION_TO_ICON } = await import(pathToFileURL(scratch).href);

// Same maths as packages/app/src/utils/color.ts desaturateHexColor.
const ICON_CHROMA = 0.65;
const toLinear = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const toSrgb = (c) => (c <= 0.0031308 ? c * 12.92 : 1.055 * c ** (1 / 2.4) - 0.055);
const channel = (c) => Math.min(255, Math.max(0, Math.round(c * 255))).toString(16).padStart(2, "0");
function desaturate(hex) {
  const body = hex.slice(1);
  const full = body.length === 3 ? [...body].map((c) => c + c).join("") : body;
  if (full.length !== 6) return hex;
  const [r, g, b] = [0, 2, 4].map((i) => toLinear(parseInt(full.slice(i, i + 2), 16) / 255));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const A = (1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s) * ICON_CHROMA;
  const B = (0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s) * ICON_CHROMA;
  const l3 = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
  const m3 = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
  const s3 = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
  return `#${channel(toSrgb(4.0767416621 * l3 - 3.3077115913 * m3 + 0.2309699292 * s3))}${channel(
    toSrgb(-1.2684380046 * l3 + 2.6097574011 * m3 - 0.3413193965 * s3),
  )}${channel(toSrgb(-0.0041960863 * l3 - 0.7034186147 * m3 + 1.707614701 * s3))}`;
}

// Drawn at 16pt; 32px keeps them sharp on 2x screens.
const PIXELS = 32;
const icons = {};
for (const [name, svg] of Object.entries(SVG_ICONS)) {
  const toned = svg.replace(/#[0-9a-fA-F]+/g, desaturate);
  const png = new Resvg(toned, { fitTo: { mode: "width", value: PIXELS } }).render().asPng();
  icons[name] = `data:image/png;base64,${Buffer.from(png).toString("base64")}`;
}

const out = `// Generated by scripts/generate-file-icons.mjs from Paseo's material-icon-theme table. Do not edit.

const ICONS: Record<string, string> = ${JSON.stringify(icons, null, 2)};

const EXTENSION_TO_ICON: Record<string, string> = ${JSON.stringify(EXTENSION_TO_ICON, null, 2)};

/** The PNG data URI of a file's type icon, picked by extension like Paseo's Changes panel. */
export function fileIconUri(fileName: string): string {
  const dot = fileName.lastIndexOf(".");
  const extension = dot === -1 || dot === fileName.length - 1 ? null : fileName.slice(dot + 1).toLowerCase();
  const icon = extension ? EXTENSION_TO_ICON[extension] : undefined;
  return (icon && ICONS[icon]) || ICONS._default;
}
`;
writeFileSync(new URL("../client/file-icons.ts", import.meta.url), out);
console.log(`Wrote ${Object.keys(icons).length} icons, ${Math.round(out.length / 1024)} KB`);
